/**
 * Escapes HTML special characters in user-supplied strings before
 * interpolating them into email templates.
 */
export function h(str: string): string {
	return str
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;')
		.replace(/'/g, '&#39;');
}
